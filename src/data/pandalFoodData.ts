/**
 * Returns food recommendations for a given pandal, customized by Pandal ID or Region
 */
export function getPandalFoodRecommendations(
  pandalId: string,
  region: Region = 'NORTH'
): FoodRecommendation[] {
  if (PANDAL_FOOD_REGISTRY[pandalId] && PANDAL_FOOD_REGISTRY[pandalId].length > 0) {
    return PANDAL_FOOD_REGISTRY[pandalId];
  }
  return REGIONAL_FOOD_FALLBACKS[region] || REGIONAL_FOOD_FALLBACKS.NORTH;
}
